const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

Object.values(TERMS).forEach(a => a.sort((x, y) => y[0].length - x[0].length));

const RULES: Record<'ta' | 'hi', [RegExp, string][]> = { ta: [], hi: [] };
(['ta', 'hi'] as const).forEach(l => {
  RULES[l] = TERMS[l].map(([en, loc]) => [
    new RegExp(`(?<![A-Za-z0-9@._/%])${escape(en)}(?![A-Za-z0-9@_/])`, 'g'),
    loc,
  ]);
});

/** Replaces known brand names, acronyms and person names with their localised form. */
export const localizeTerms = (lang: Language, text: string): string => {
  if (lang === 'en' || !/[A-Za-z]/.test(text)) return text;
  let out = text;
  for (const [re, loc] of RULES[lang]) out = out.replace(re, loc);
  return out;
};
